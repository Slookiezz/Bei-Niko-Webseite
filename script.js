// ─── Language ─────────────────────────────────────────────────────────────────
var currentLang = localStorage.getItem('lang') || 'de';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.getElementById('htmlRoot').lang = lang;

  var t = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  document.querySelectorAll('.lang-btn').forEach(function(btn) {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Re-render maps overlay only if still in consent state (not loaded)
  var wrapper = document.getElementById('mapsWrapper');
  if (wrapper && document.getElementById('mapsOverlay')) {
    wrapper.innerHTML = getMapsOverlayHTML();
  }

  loadMenu();
}

// ─── Google Maps ──────────────────────────────────────────────────────────────
var MAPS_IFRAME_SRC = 'https://www.google.com/maps/embed?pb=!1m18!1m12!1m3!1d2436.399439768524!2d9.910495100000002!3d52.3631768!2m3!1f0!2f0!3f0!3m2!1i1024!2i768!4f13.1!3m3!1m2!1s0x47b00906debb214d%3A0x2f6444c96cf40568!2sBei%20Niko!5e0!3m2!1sde!2sde!4v1774947200820!5m2!1sde!2sde';

function getMapsOverlayHTML() {
  var t = translations[currentLang];
  return '<div class="maps-consent-overlay" id="mapsOverlay">'
    + '<p>' + t['maps.text'] + '</p>'
    + '<div class="maps-consent-buttons">'
    + '<button onclick="loadGoogleMaps()" class="btn-maps-consent">' + t['maps.load'] + '</button>'
    + '<button onclick="denyGoogleMaps()" class="btn-maps-deny">' + t['maps.deny'] + '</button>'
    + '</div>'
    + '<a href="https://policies.google.com/privacy" target="_blank" rel="noopener" class="maps-privacy-link">' + t['maps.privacy'] + '</a>'
    + '</div>';
}

function getMapsIframeHTML() {
  var t = translations[currentLang];
  return '<iframe src="' + MAPS_IFRAME_SRC + '" style="border:0;" allowfullscreen="" loading="lazy" referrerpolicy="no-referrer-when-downgrade"></iframe>'
    + '<button class="btn-maps-revoke" onclick="revokeGoogleMaps()" title="' + t['maps.revoke.title'] + '">&#x21BA; ' + t['maps.revoke'] + '</button>';
}

function getMapsDeniedHTML() {
  var t = translations[currentLang];
  return '<div class="maps-consent-overlay" id="mapsOverlay">'
    + '<p style="color:rgba(245,240,232,0.45);font-size:0.85rem;">' + t['maps.denied.text']
    + ' <button onclick="resetGoogleMaps()" class="btn-maps-reset">' + t['maps.reset'] + '</button></p>'
    + '</div>';
}

function loadGoogleMaps() {
  localStorage.setItem('maps_consent', 'accepted');
  document.getElementById('mapsWrapper').innerHTML = getMapsIframeHTML();
}

function denyGoogleMaps() {
  localStorage.setItem('maps_consent', 'denied');
  document.getElementById('mapsWrapper').innerHTML = getMapsDeniedHTML();
}

function revokeGoogleMaps() {
  localStorage.removeItem('maps_consent');
  document.getElementById('mapsWrapper').innerHTML = getMapsOverlayHTML();
}

function resetGoogleMaps() {
  localStorage.removeItem('maps_consent');
  document.getElementById('mapsWrapper').innerHTML = getMapsOverlayHTML();
}

(function() {
  var consent = localStorage.getItem('maps_consent');
  if (consent === 'accepted') {
    document.getElementById('mapsWrapper').innerHTML = getMapsIframeHTML();
  } else if (consent === 'denied') {
    document.getElementById('mapsWrapper').innerHTML = getMapsDeniedHTML();
  }
})();

// ─── Legal modals ─────────────────────────────────────────────────────────────
function openLegal(id) {
  document.getElementById(id).classList.add('active');
  document.body.style.overflow = 'hidden';
}
function closeLegal(id) {
  document.getElementById(id).classList.remove('active');
  document.body.style.overflow = '';
}
document.addEventListener('keydown', function(e) {
  if (e.key === 'Escape') {
    document.querySelectorAll('.legal-overlay.active').forEach(function(el) {
      closeLegal(el.id);
    });
  }
});
document.querySelectorAll('.legal-overlay').forEach(function(overlay) {
  overlay.addEventListener('click', function(e) {
    if (e.target === this) closeLegal(this.id);
  });
});

// ─── Betriebsferien Banner ────────────────────────────────────────────────────
var BANNER_ENABLED = false; // true = Banner aktiv, false = Banner deaktiviert
var BANNER_KEY = 'banner_dismissed_2026_08';

function closeBanner() {
  document.getElementById('bannerOverlay').classList.remove('active');
  document.body.style.overflow = '';
  sessionStorage.setItem(BANNER_KEY, 'true');
}

if (BANNER_ENABLED && !sessionStorage.getItem(BANNER_KEY)) {
  document.getElementById('bannerOverlay').classList.add('active');
  document.body.style.overflow = 'hidden';
}

document.getElementById('bannerOverlay').addEventListener('click', function(e) {
  if (e.target === this) closeBanner();
});

document.addEventListener('keydown', function(e) {
  if (e.key === 'Escape' && document.getElementById('bannerOverlay').classList.contains('active')) {
    closeBanner();
  }
});

